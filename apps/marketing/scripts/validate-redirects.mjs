#!/usr/bin/env node

/**
 * Validates the trailing-slash 301 rules in public/_redirects against the
 * actual prerendered routes (scripts/redirects-lib.mjs enumeration) — the
 * drift guard for the routing architecture from PR #592: prerendered pages
 * cannot be canonicalised by Astro middleware or the fetch entrypoint, so
 * every page needs an explicit asset-layer rule. Without this check the next
 * published page silently falls through to the platform 307.
 *
 * Default mode: fail on any missing rule, orphan rule or wrong target.
 * --write: regenerate the trailing-slash and /index.html blocks in place
 * (deterministic output; the hand-maintained legacy redirects above the
 * blocks are preserved verbatim).
 */

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import { allRoutes } from "./redirects-lib.mjs"

const here = dirname(fileURLToPath(import.meta.url))
const redirectsPath = join(here, "../public/_redirects")

const HEADER = `# Trailing-slash canonicalisation for prerendered pages. Astro's trailingSlash
# config only redirects on-demand rendered routes; prerendered pages are the
# hosting platform's job (Astro docs: "You cannot use Astro redirects for this
# use case"). These explicit 301 rules run at the Workers static-assets layer.
# GENERATED by scripts/validate-redirects.mjs --write from the route
# enumeration in scripts/redirects-lib.mjs — do not hand-edit this block; add
# pages and rerun the writer (or let CI catch the gap).`

const INDEX_HEADER = `# /index.html forms of the main pages: the platform serves them 200 under
# drop-trailing-slash; canonicalise permanently instead.`

function parseRules(source) {
  const rules = []
  for (const line of source.split("\n")) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith("#")) continue
    const parts = trimmed.split(/\s+/)
    if (parts.length >= 3) rules.push({ source: parts[0], target: parts[1], code: parts[2] })
  }
  return rules
}

/** Split the file into: legacy region (kept verbatim), TS block, index.html block. */
function splitFile(source) {
  const lines = source.split("\n")
  const tsStart = lines.findIndex((line) => line.trim() === "/pricing/ /pricing 301")
  if (tsStart === -1) return { legacy: source, tsBlock: null, indexBlock: null }
  return { lines, tsStart }
}

function generateBlocks(routes) {
  const mainPages = routes.filter((route) => route.split("/").length <= 2)
  const tsLines = routes.map((route) => `${route}/ ${route} 301`)
  const indexLines = mainPages.map((route) => `${route}/index.html ${route} 301`)
  const tsBlock = [HEADER, ...tsLines].join("\n")
  const indexBlock = [INDEX_HEADER, ...indexLines].join("\n")
  return { tsBlock, indexBlock }
}

function main() {
  const write = process.argv.includes("--write")
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- Repository-owned config file.
  const source = readFileSync(redirectsPath, "utf8")
  const routes = allRoutes()
  const rules = parseRules(source)
  const bySource = new Map(rules.map((rule) => [rule.source, rule]))

  const errors = []
  let checked = 0

  for (const route of routes) {
    const slashForm = `${route}/`
    checked += 1
    const rule = bySource.get(slashForm)
    if (!rule) {
      errors.push(`missing trailing-slash rule: ${slashForm} -> ${route} 301`)
      continue
    }
    if (rule.target !== route || rule.code !== "301") {
      errors.push(`wrong rule for ${slashForm}: got "${rule.source} ${rule.target} ${rule.code}", expected "${slashForm} ${route} 301"`)
    }
  }

  const routeSet = new Set(routes.map((route) => `${route}/`))
  const indexSet = new Set(
    routes.filter((route) => route.split("/").length <= 2).map((route) => `${route}/index.html`)
  )
  for (const rule of rules) {
    if (rule.source.endsWith("/") && !rule.source.includes("index.html") && !routeSet.has(rule.source)) {
      errors.push(`orphan trailing-slash rule (no such route): ${rule.source}`)
    }
    if (rule.source.endsWith("/index.html") && !indexSet.has(rule.source)) {
      errors.push(`orphan index.html rule (no such main page): ${rule.source}`)
    }
  }

  if (write) {
    const { tsBlock, indexBlock } = generateBlocks(routes)
    const legacy = source
      .split("\n")
      .slice(0, splitFile(source).tsStart === -1 ? undefined : splitFile(source).tsStart)
      .join("\n")
      .replace(/\n# Trailing-slash canonicalisation[\s\S]*$/, "")
      .replace(/\n+$/, "")
    const next = `${legacy}\n\n${tsBlock}\n\n${indexBlock}\n`
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- Repository-owned config file.
    writeFileSync(redirectsPath, next)
    console.log(`Wrote ${routes.length} trailing-slash rules + index.html rules to public/_redirects`)
    if (errors.length > 0) {
      console.error(`Fixed ${errors.length} gap(s) by regeneration:`)
      for (const error of errors) console.error(`- ${error}`)
    }
    return
  }

  if (errors.length > 0) {
    console.error(`Redirects validation failed (${errors.length} violation(s)):`)
    for (const error of errors) console.error(`- ${error}`)
    console.error("")
    console.error("Fix: run `node scripts/validate-redirects.mjs --write` and commit the result.")
    process.exit(1)
  }

  console.log(`Redirects validation passed: ${checked} routes, every rule present and correct.`)
}

main()
