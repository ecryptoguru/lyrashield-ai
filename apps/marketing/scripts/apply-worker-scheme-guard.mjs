#!/usr/bin/env node
// VULN-P-001 — enforce https at the Worker boundary.
//
// Live probe showed http://lyrashieldai.com/ serving content (200) with no
// redirect. Astro middleware cannot fix it: the adapter's generated worker
// short-circuits to static assets before app.render() ever runs, so
// middleware only sees SSR/API routes. The enforcement must sit at the
// worker fetch() boundary.
//
// The @astrojs/cloudflare build emits dist/server/entry.mjs (the deployed
// `main`). This script renames it to entry.generated.mjs and installs a thin
// wrapper entry that 301s any http: request to https: before delegating —
// every request, static or dynamic, passes through it. Idempotent: re-run
// safe. Fails closed if the generated entry shape changes.

import { existsSync, readFileSync, renameSync, writeFileSync } from "node:fs"

const serverDir = new URL("../dist/server/", import.meta.url)
const entry = new URL("entry.mjs", serverDir)
const generated = new URL("entry.generated.mjs", serverDir)

if (!existsSync(entry) && !existsSync(generated)) {
  throw new Error("dist/server/entry.mjs missing — run `astro build` first")
}

if (!existsSync(generated)) {
  renameSync(entry, generated)
}

const generatedSource = readFileSync(generated, "utf8")
if (!generatedSource.includes("fetch")) {
  throw new Error(
    "generated worker entry no longer exports a fetch handler — the scheme guard cannot wrap it"
  )
}

const WRAPPER = `// Generated by scripts/apply-worker-scheme-guard.mjs (VULN-P-001).
// Do not edit — this file is rewritten on every build.
import generated from "./entry.generated.mjs"

export default {
  fetch(request, env, ctx) {
    const url = new URL(request.url)
    if (url.protocol === "http:") {
      // Local dev (wrangler dev/miniflare) serves plain http — exempt
      // loopback hosts or every local request would redirect-loop.
      const loopback =
        url.hostname === "localhost" ||
        url.hostname === "127.0.0.1" ||
        url.hostname === "[::1]" ||
        url.hostname.endsWith(".localhost")
      if (!loopback) {
        url.protocol = "https:"
        return Response.redirect(url.toString(), 301)
      }
    }
    return generated.fetch(request, env, ctx)
  },
}
`

writeFileSync(entry, WRAPPER)
console.log("Installed https scheme guard at dist/server/entry.mjs")
